// Sort keys longest-first so full phrases always translate before sub-phrases
window._VI_EN_KEYS = Object.keys(window.VI_EN_DICT).sort((a, b) => b.length - a.length);

window.applyFullLanguageDOM = function (lang, root = document.body) {
  if (!root) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, null);
  let node;
  while ((node = walker.nextNode())) {
    const parent = node.parentElement;
    if (!parent || parent.tagName === "SCRIPT" || parent.tagName === "STYLE") continue;
    if (node._viOrig === undefined) {
      node._viOrig = node.nodeValue;
    }
    if (lang === "vi") {
      node.nodeValue = node._viOrig;
    } else {
      const raw = node._viOrig;
      const trimmed = raw.trim();
      if (!trimmed) continue;
      if (window.VI_EN_DICT[trimmed]) {
        node.nodeValue = raw.replace(trimmed, window.VI_EN_DICT[trimmed]);
      } else {
        let out = raw;
        for (const k of window._VI_EN_KEYS) {
          if (out.includes(k)) {
            out = out.split(k).join(window.VI_EN_DICT[k]);
          }
        }
        node.nodeValue = out;
      }
    }
  }

  root.querySelectorAll("[placeholder], [title]").forEach((el) => {
    if (el.hasAttribute("placeholder")) {
      if (el._viPlaceholder === undefined) el._viPlaceholder = el.getAttribute("placeholder");
      const orig = el._viPlaceholder;
      el.setAttribute("placeholder", lang === "vi" ? orig : (window.VI_EN_DICT[orig] || orig));
    }
    if (el.hasAttribute("title")) {
      if (el._viTitle === undefined) el._viTitle = el.getAttribute("title");
      const origT = el._viTitle;
      el.setAttribute("title", lang === "vi" ? origT : (window.VI_EN_DICT[origT] || origT));
    }
  });
};
